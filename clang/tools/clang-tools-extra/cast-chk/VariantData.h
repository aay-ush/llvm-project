struct VariantFieldData {
    bool isFptr_;
    std::string name_;
    std::string value_;
    OpLocation location_;
};

using VariantKey = std::string;
struct VariantData {
    VariantKey name_;
    OpLocation location_;
    std::unordered_map<std::string, VariantFieldData> attrs_;    // attr: <enum field> = <enum field's value>
};
std::unordered_map<std::string, VariantData> Variants;

std::string variantFieldTag(VariantFieldData const &field) {
    std::string tag = field.name_;
    std::string suffix = " sub)";
    if(field.isFptr_) {
        auto ppos = field.name_.find_last_of('(');
        if(ppos != std::string::npos) {
            tag.replace(ppos, 1, "(*sub)(");
            suffix = ")";
        }
    }
    return tag + suffix;
}

std::vector<std::string> makeVariantAnnotations(VariantData const &vd) {
    // Tag format
    // int __ENUM_Shape_2(struct Shape base, struct Rectangle sub) { return 0; }
    //           |_fn_|  |------base--------|-----subtype----|
    // |-------prefix--|n|-----------------------------------|--^--|--suffix---|
    //
    auto fn = vd.name_;
    std::string toDelete = "struct "; // Don't include struct in fn name
    if(auto pos = fn.find(toDelete); pos != std::string::npos) {
        fn.replace(pos, toDelete.size(), "");
    }
    std::string prefix = "int __ENUM_" + fn + "_";
    std::string base = "(" + vd.name_ + " base, ";
    std::string suffix = " { return 0; }\n";

    unsigned n = 0;
    std::vector<std::string> tags;
    tags.reserve(vd.attrs_.size());
    for(auto const &[field, fdata]: vd.attrs_) {
        std::string tag = prefix + std::to_string(n)    // fn
                            + base                      // base param
                            + variantFieldTag(fdata)    // subtype param
                            + suffix;                   // body
        tags.push_back(tag);
        n++;
    }
    return tags;
}

std::string blockAnnotation(std::vector<VariantKey> const &variants) {
    std::string insertPrefix = "\n// Tags generated by TCC //\n";

    auto nbTags = std::accumulate(begin(variants), end(variants), 0,
            [](unsigned count, auto const &v) {
                return count + Variants[v].attrs_.size();
            });
    std::vector<std::string> tags;
    tags.reserve(nbTags);

    for(auto const &v: variants) {
        auto vtags = (makeVariantAnnotations(Variants[v]));
        tags.insert(std::end(tags), std::begin(vtags), std::end(vtags));
    }
    std::string annotation;
    for(auto const &t: tags) {
        annotation += t;
    }

    std::string insertSuffix = "// end Tags generated by TCC //\n";
    return insertPrefix + annotation + insertSuffix;
}

llvm::Expected<Replacements> eofVariantBlockAnnotation(clang::SourceManager const &sm,
        FileID fid,
        std::vector<VariantKey> const &variants) {

    auto insertLoc = sm.getLocForEndOfFile(fid);
    Replacements repls;
    auto err = repls.add(Replacement(sm, insertLoc, 0, blockAnnotation(variants)));
    if(err) {
        auto fp = sm.getFilename(insertLoc);
        CNS_ERROR("BlockRepl", "Could not schedule block annotation insertion for {}", fp.str());
        return err;
    }
    return repls;
}

