llvm::ErrorOr<std::string> variantTaggedRelativeOutPath(std::string const &fp, std::string const &outdir) {
    constexpr auto logKey = "VariantTaggedOutfile";

    llvm::SmallString<256> current;
    auto err = llvm::sys::fs::current_path(current);
    if(err) {
        CNS_ERROR(logKey, "Failed to get current path: {}", err.message());
        return err;
    }
    std::string common = current.c_str();
    CNS_DEBUG(logKey, "current path: {}", common);

    std::string outfile = outdir + "/" + fp;
    if(auto pos = fp.find(common); pos != std::string::npos) {
        // remove common path prefix
        CNS_DEBUG(logKey, "Relative path: ./{}", fp.substr(common.size()));
        outfile = outdir + fp.substr(common.size());
    }
    CNS_DEBUG(logKey, "Outfile path: {}", outfile);
    return outfile;
}

llvm::ErrorOr<std::string> prepVariantTaggedOutDir(std::string const &fp, std::string const &outdir) {
    constexpr auto logKey = "VariantTaggedOutfile";
    auto err = llvm::sys::fs::create_directories(outdir);
    if(err) {
        CNS_ERROR(logKey, "Create directory failed for {}: {}", outdir, err.message());
        return err;
    }

    auto outfile_ = variantTaggedRelativeOutPath(fp, outdir);
    if(!outfile_) {
        CNS_ERROR(logKey, "Cannot determine outfile path for {}: {}", fp, outfile_.getError().message());
        return outfile_.getError();
    }
    auto outfile = *outfile_;
    CNS_DEBUG(logKey, "Outfile path: {}", outfile);

    auto outdirs = outfile.substr(0, outfile.find_last_of('/'));
    if(outdir != outdirs) {
        // Create dirs in outfile path
        auto rc = llvm::sys::fs::create_directories(outdirs);
        if(rc) {
            CNS_ERROR(logKey, "Create directories failed for {}: {}", outdirs, rc.message());
            return rc;
        }
    }

    err = llvm::sys::fs::copy_file(fp, outfile);
    if(err) {
        CNS_ERROR(logKey, "File copy from {} to {} failed: {}", fp, outfile, err.message());
        return err;
    }
    return outfile;
}

void createVariantAnnotatedVersion(std::string fp, std::string outdir, std::string const &code) {
    constexpr auto logKey = "VariantTaggedOutfile";
    auto outfile_ = prepVariantTaggedOutDir(fp, outdir);
    if(!outfile_) {
        CNS_ERROR(logKey, "Error during variant tagged outfile creation for ({}) in outdir {}: {}", fp, outdir, outfile_.getError().message());
        return;
    }
    auto outfile = *outfile_;
    std::error_code rc;
    llvm::raw_fd_ostream os(outfile, rc, llvm::sys::fs::OF_Text);
    if(rc) {
        CNS_ERROR(logKey, "Write failed for {}: {}", outfile, rc.message());
        return;
    }
    os << code;
}

using FileToVariantsMap = std::unordered_map<std::string, std::vector<std::string>>;

void insertVariantTagsInMatchingSources(
        clang::SourceManager &sm,
        FileToVariantsMap const &variantsByFile,
        std::string const &outDir) {

    constexpr auto logKey = "InsertTag";
    for(auto it = sm.fileinfo_begin(); it != sm.fileinfo_end(); ++it) {
        auto const feref = it->first;
        auto const fname = realPathFromFileEntryRef(sm, feref);

        if(variantsByFile.find(fname) == std::end(variantsByFile)) {
            CNS_ERROR(logKey, "No variants found for filename {}", fname);
            continue;
        }

        auto fid = sm.getOrCreateFileID(feref, clang::SrcMgr::C_User);

        auto updatedCode = addVariantTagsToSourceBuffer(sm, fid, feref, fname, variantsByFile.at(fname));
        if(!updatedCode) {
            CNS_ERROR(logKey, "Variants annotation in source buffer failed for {}: {}", fname, llvm::toString(updatedCode.takeError()));
            continue;
        }
        createVariantAnnotatedVersion(fname, outDir, *updatedCode);
    }
}

